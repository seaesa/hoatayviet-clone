const LANG_KEY = "htv-lang";

function getLang() {
  return localStorage.getItem(LANG_KEY) || "vi";
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  applyLang(lang);
}

function t(key, lang) {
  const entry = I18N[key];
  if (!entry) return key;
  return entry[lang || getLang()] || entry.vi;
}

function applyLang(lang) {
  document.documentElement.lang = lang === "en" ? "en" : "vi";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"), lang);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder"), lang));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"), lang));
  });
  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.textContent = lang === "en" ? "VI" : "EN";
    btn.setAttribute("aria-label", lang === "en" ? "Chuyển sang tiếng Việt" : "Switch to English");
  });
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
  // The HTML already ships the real Vietnamese copy as static markup — it is
  // the source of truth, not a placeholder. So on a fresh/default ("vi")
  // load we deliberately do NOT touch the DOM: with JS disabled, or before
  // this line ever runs, the page already reads correctly end to end. JS
  // only rewrites text when the visitor has actually asked for English.
  if (getLang() === "en") applyLang("en");
  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.addEventListener("click", () => setLang(getLang() === "en" ? "vi" : "en"));
  });
});
