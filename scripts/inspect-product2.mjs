import { fetchSmart, loadCheerio } from './fetch-utils.mjs';

const url = process.argv[2];
const { html, source } = await fetchSmart(url);
console.log('SOURCE', source, 'LEN', html ? html.length : 0);
if (!html) process.exit(0);
const $ = loadCheerio(html);
console.log('TITLE', $('title').text());
console.log('H1', $('h1').first().text().trim());
console.log('--- breadcrumb ---');
$('.woocommerce-breadcrumb, nav.woocommerce-breadcrumb').each((i,el)=>console.log($(el).text().replace(/\s+/g,' ').trim()));
console.log('--- price ---');
$('.summary .price').each((i,el)=>console.log(i, $(el).text().replace(/\s+/g,' ').trim()));
console.log('--- gallery images ---');
$('.woocommerce-product-gallery__image img, .woocommerce-product-gallery img').each((i,el)=>console.log(i, $(el).attr('data-src')||$(el).attr('src')));
console.log('--- short description ---');
console.log($('.woocommerce-product-details__short-description').text().replace(/\s+/g,' ').trim().slice(0,400));
